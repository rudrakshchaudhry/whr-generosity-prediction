"""Render ``metrics.json`` as Markdown tables (also pasted into the README)."""

from __future__ import annotations

from .plots import MODEL_LABELS

SCHEME_TITLES = {
    "random": "5-fold random CV",
    "grouped": "5-fold CV grouped by country",
}


def _fmt(x: float, digits: int) -> str:
    # round first and add 0.0 so tiny negatives print as 0.000, not -0.000
    return f"{round(x, digits) + 0.0:.{digits}f}"


def _pm(mean: float, std: float, digits: int = 3) -> str:
    return f"{_fmt(mean, digits)} ± {_fmt(std, digits)}"


def cv_table(metrics: dict, scheme: str = "random") -> str:
    """One row per model: R^2, MSE and MAE as mean ± std over outer folds."""
    rows = metrics["cv"][scheme]
    lines = [
        f"| Model ({SCHEME_TITLES[scheme]}) | R² | MSE | MAE |",
        "|---|---|---|---|",
    ]
    for name, r in rows.items():
        lines.append(
            f"| {MODEL_LABELS.get(name, name)} "
            f"| {_pm(r['r2_mean'], r['r2_std'])} "
            f"| {_pm(r['mse_mean'], r['mse_std'], 4)} "
            f"| {_pm(r['mae_mean'], r['mae_std'], 4)} |"
        )
    return "\n".join(lines)


def original_table(metrics: dict) -> str:
    """The original notebook's single random 75/25 split, reproduced."""
    o = metrics["original_protocol"]
    lines = [
        "| Model (random 75/25 split) | R² | MSE |",
        "|---|---|---|",
        f"| Linear regression | {_fmt(o['linear_regression']['r2'], 3)} "
        f"| {_fmt(o['linear_regression']['mse'], 4)} |",
        f"| Random forest (defaults) | {_fmt(o['random_forest']['r2'], 3)} "
        f"| {_fmt(o['random_forest']['mse'], 4)} |",
    ]
    return "\n".join(lines)


def importance_table(metrics: dict) -> str:
    best = metrics["best_model"]
    pi = metrics["permutation_importance"][best]
    rows = sorted(pi.items(), key=lambda kv: kv[1]["mean"], reverse=True)
    lines = ["| Feature | Drop in R² when permuted (mean ± std over folds) |", "|---|---|"]
    lines += [f"| {k} | {_pm(v['mean'], v['std'])} |" for k, v in rows]
    return "\n".join(lines)


def render_markdown(metrics: dict) -> str:
    c = metrics["config"]
    d = metrics["data_summary"]
    primary = c["primary_scheme"]
    out = [
        "# Results",
        "",
        "Generated by `python -m whr_generosity`. Do not edit by hand.",
        "",
        f"- Rows with a Generosity value: {d['n_rows']} "
        f"({d['n_countries']} countries, {d['year_min']}-{d['year_max']})",
        f"- Outer folds: {c['n_outer_splits']} x {c['n_repeats']} repeats; "
        f"inner folds: {c['n_inner_splits']}; seed: {c['seed']}; quick mode: {c['quick']}",
        "",
        "## Random 75/25 split (original protocol, reproduced)",
        "",
        original_table(metrics),
        "",
    ]
    for scheme in metrics["cv"]:
        out += [
            f"## {SCHEME_TITLES[scheme]}, nested (mean ± std over all outer folds)",
            "",
            cv_table(metrics, scheme),
            "",
        ]
    out += [
        f"Best model ({SCHEME_TITLES[primary]}): **{MODEL_LABELS.get(metrics['best_model'])}**",
        "",
        f"## Permutation importance (best model, held-out folds of {SCHEME_TITLES[primary]})",
        "",
        importance_table(metrics),
        "",
    ]
    return "\n".join(out)
